import { readFile, writeFile, mkdir, copyFile, stat } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const plan = JSON.parse(await readFile(join(root, "assets/card-plan.json"), "utf8"));
const themes = JSON.parse(await readFile(join(root, "assets/theme-catalog.json"), "utf8"));
const codes = [...new Set(themes.flatMap((theme) => theme.pairs.flatMap((pair) => [pair.left, pair.right])).filter((face) => face.image.startsWith("/cards/flags/")).map((face) => face.image.split("/").pop().slice(0, -4)))];
await mkdir(join(root, "public/cards/flags"), { recursive: true });
for (const code of codes) await copyFile(join(root, "node_modules/flag-icons/flags/4x3", code + ".svg"), join(root, "public/cards/flags", code + ".svg"));
await copyFile(join(root, "node_modules/flag-icons/LICENSE"), join(root, "public/cards/flags/LICENSE.txt"));
const exists = async (file) => { try { return (await stat(file)).size > 0; } catch { return false; } };
let ready = 0;
for (const item of plan.items) {
  const source = join(root, "assets/cards", item.theme, item.id + ".png");
  const output = join(root, "public/cards", item.theme, item.id + ".webp");
  if (await exists(source)) {
    await mkdir(dirname(output), { recursive: true });
    if (!await exists(output) || (await stat(source)).mtimeMs > (await stat(output)).mtimeMs) {
      const stats = await sharp(source).stats();
      if (stats.isOpaque) throw new Error("Transparent background missing: " + source);
      await sharp(source).trim({ threshold: 8 }).resize(272, 272, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).extend({ top: 24, bottom: 24, left: 24, right: 24, background: { r: 0, g: 0, b: 0, alpha: 0 } }).webp({ quality: 84, alphaQuality: 90 }).toFile(output);
    }
  }
  if (await exists(output)) {
    const metadata = await sharp(output).metadata();
    if (metadata.format !== "webp" || metadata.width !== 320 || metadata.height !== 320 || !metadata.hasAlpha) throw new Error("Invalid optimized card: " + output);
    if (process.argv.includes("--complete") && (await sharp(output).stats()).isOpaque) throw new Error("Opaque card background: " + output);
    ready++;
  }
}

const available = {};
for (const theme of themes) {
  available[theme.id] = [];
  for (const pair of theme.pairs) {
    if (await exists(join(root, "public", pair.left.image)) && await exists(join(root, "public", pair.right.image))) available[theme.id].push(pair.id);
  }
}
await writeFile(join(root, "src/data/readyPairs.ts"), ["// Generated by scripts/prepare-assets.mjs; do not edit.", "export const readyPairIds: Record<string, string[]> = " + JSON.stringify(available, null, 2) + ";", ""].join("\n"));
console.log("Card illustrations: " + ready + "/" + plan.items.length + ". Flags: " + codes.length + ".");
const incomplete = themes.filter((theme) => available[theme.id].length !== theme.pairs.length);
if (process.argv.includes("--complete") && (ready !== plan.items.length || incomplete.length)) {
  console.error("Incomplete card assets:", incomplete.map((theme) => theme.id + " " + available[theme.id].length + "/" + theme.pairs.length).join(", "));
  process.exitCode = 1;
}
